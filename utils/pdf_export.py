def _show_preview(parent, title: str, html: str):
    doc = QTextDocument()
    doc.setHtml(html)
    printer = QPrinter(QPrinter.PrinterMode.HighResolution)
    printer.setPageMargins(QMarginsF(15, 15, 15, 15), QPrinter.Unit.Millimeter)
    dlg = QPrintPreviewDialog(printer, parent)
    dlg.setWindowTitle(f"Print Preview — {title}")
    dlg.resize(950, 720)
    dlg.paintRequested.connect(lambda p: doc.print(p))
    dlg.exec()


# ── Receipt ───────────────────────────────────────────────────────────────────

def print_receipt(parent, data: dict):
    """Show print-preview for a single payment receipt."""
    bal = max(data.get("balance", 0), 0)
    st  = data.get("status", "")
    st_cls = {"paid": "status-paid", "partial": "status-partial",
              "unpaid": "status-unpaid"}.get(st, "")

    body = f"""
<div class="kv"><b>Receipt No:</b> <span class="bold">{data.get('receipt_no','—')}</span></div>
<div class="kv"><b>Control No:</b> {data.get('control_number','—')}</div>
<hr class="thin">
<div class="kv"><b>Student Name:</b> {data.get('student','—')}</div>
<div class="kv"><b>Admission No:</b> {data.get('admission_no','—')}</div>
<div class="kv"><b>Class:</b> {data.get('class_name','—')}</div>
<div class="kv"><b>Fee Type:</b> {data.get('fee_name','—')}</div>
<hr class="thin">
<div class="kv"><b>Amount Paid:</b>
  <span class="amount">TZS {data.get('amount_paid',0):,.0f}</span></div>
<div class="kv"><b>Payment Method:</b> {data.get('payment_method','Cash')}</div>
<div class="kv"><b>Reference No:</b> {data.get('reference_no','') or '—'}</div>
<div class="kv"><b>Payment Date:</b> {data.get('payment_date','—')}</div>
<div class="kv"><b>Recorded By:</b> {data.get('recorded_by','—')}</div>
<hr class="thin">
<div class="kv"><b>Total Billed:</b> TZS {data.get('amount_due',0):,.0f}</div>
<div class="kv"><b>Discount/Waiver:</b> TZS {data.get('discount_amount',0):,.0f}</div>
<div class="kv"><b>Balance Remaining:</b> TZS {bal:,.0f}</div>
<div class="kv"><b>Bill Status:</b>
  <span class="{st_cls}">{st.upper()}</span></div>
"""
    html = _page_html("Payment Receipt", body)
    _show_preview(parent, "Payment Receipt", html)


# ── Generic table export ──────────────────────────────────────────────────────

def export_table(parent, title: str, columns: list, rows: list,
                 summary_html: str = ""):
    """Export any QTableWidget-style data as a printable table."""
    thead = "".join(f"<th>{c}</th>" for c in columns)
    tbody = ""
    for row in rows:
        tbody += "<tr>" + "".join(f"<td>{v}</td>" for v in row) + "</tr>"
    body = (
        (f'<div class="section">{title}</div>' if summary_html else "")
        + summary_html
        + f"<table><thead><tr>{thead}</tr></thead><tbody>{tbody}</tbody></table>"
    )
    html = _page_html(title, body)
    _show_preview(parent, title, html)


# ── Finance report ────────────────────────────────────────────────────────────

def print_finance_report(parent, year_label: str, stats: dict, rows: list):
    """rows: list of dicts with keys class_name, students, billed, collected,
             outstanding, waived, rate"""
    rate_str = stats.get("rate", "N/A")
    summary = f"""
<div class="section">Summary — {year_label}</div>
<table>
<tr>
  <th>Total Billed</th><th>Collected</th>
  <th>Outstanding</th><th>Waived</th>
  <th>Collection Rate</th><th>Exempt Students</th>
</tr>
<tr>
  <td>TZS {stats.get('billed',0):,.0f}</td>
  <td class="green">TZS {stats.get('collected',0):,.0f}</td>
  <td class="red">TZS {stats.get('outstanding',0):,.0f}</td>
  <td class="orange">TZS {stats.get('waived',0):,.0f}</td>
  <td class="bold">{rate_str}</td>
  <td>{stats.get('orphans',0)}</td>
</tr>
</table>
"""
    cols = ["Class", "Students Billed", "Billed (TZS)", "Collected (TZS)",
            "Outstanding (TZS)", "Waived (TZS)", "Rate"]
    table_rows = [
        [r["class_name"], r["students"], f"{r['billed']:,.0f}",
         f"{r['collected']:,.0f}", f"{r['outstanding']:,.0f}",
         f"{r['waived']:,.0f}", r["rate"]]
        for r in rows
    ]
    thead = "".join(f"<th>{c}</th>" for c in cols)
    tbody = "".join(
        "<tr>" + "".join(f"<td>{v}</td>" for v in row) + "</tr>"
        for row in table_rows
    )
    body = (
        summary
        + '<div class="section">Breakdown by Class</div>'
        + f"<table><thead><tr>{thead}</tr></thead><tbody>{tbody}</tbody></table>"
    )
    html = _page_html("Finance Report", body)
    _show_preview(parent, "Finance Report", html)


