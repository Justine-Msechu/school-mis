# ── Inventory report ──────────────────────────────────────────────────────────

def print_inventory_report(parent, stats: dict, rows: list):
    summary = f"""
<div class="section">Summary</div>
<table>
<tr><th>Total Items</th><th>Low Stock</th><th>Total Issued</th><th>Stock Value</th></tr>
<tr>
  <td>{stats.get('items',0)}</td>
  <td class="red">{stats.get('low',0)}</td>
  <td>{stats.get('issued',0)}</td>
  <td class="green">TZS {stats.get('value',0):,.0f}</td>
</tr>
</table>
"""
    cols = ["Item", "Category", "Unit Price", "In Stock", "Reorder",
            "Issued", "Returned", "Stock Value", "Status"]
    table_rows = [
        [r["name"], r["category"],
         f"{r['unit_price']:,.0f}", str(r["stock_qty"]),
         str(r["reorder_qty"]), str(r["issued"]), str(r["returned"]),
         f"{r['stock_qty']*r['unit_price']:,.0f}",
         "LOW STOCK" if r["stock_qty"] <= r["reorder_qty"] else "OK"]
        for r in rows
    ]
    thead = "".join(f"<th>{c}</th>" for c in cols)
    tbody = "".join(
        "<tr>" + "".join(
            f'<td{"  class=\"red\"" if v=="LOW STOCK" else ""}>{v}</td>'
            for v in row
        ) + "</tr>"
        for row in table_rows
    )
    body = (
        summary
        + '<div class="section">Stock Level by Item</div>'
        + f"<table><thead><tr>{thead}</tr></thead><tbody>{tbody}</tbody></table>"
    )
    html = _page_html("Inventory Report", body)
    _show_preview(parent, "Inventory Report", html)
